"""Atomic forensic report generation, independent from the GUI."""
from __future__ import annotations

import hashlib
import os
import tempfile
from collections.abc import Callable
from datetime import datetime
from pathlib import Path

from .config import APP_TITLE, REPORT_FORMAT_VERSION, SAVE_PROGRESS_EVERY_ROWS
from .models import ScanOptions, ScanResult
from .utils import format_size, normalize_domain, safe_report_text

ReportProgressCallback = Callable[[int, int], None]


def write_forensic_report(
    output_path: Path,
    result: ScanResult,
    options: ScanOptions,
    progress_callback: ReportProgressCallback | None = None,
) -> str:
    """Write a report atomically and return the SHA-256 of data lines."""
    output_path = Path(output_path)
    root = options.root_path.resolve()
    destination = output_path.resolve()
    if destination == root or root in destination.parents:
        raise ValueError("Save the report outside the scanned source directory")

    parent = output_path.parent
    if not parent.exists():
        raise OSError(f"Destination directory does not exist: {parent}")

    digest = hashlib.sha256()
    temporary_path: Path | None = None
    aggressive_magic = options.aggressive_magic or options.deep_mode == "ultra"

    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=parent,
            prefix=f".{output_path.name}.",
            suffix=".tmp",
            delete=False,
        ) as temp:
            temporary_path = Path(temp.name)
            c = result.counters
            temp.write(f"# REPORT FORMAT VERSION: {REPORT_FORMAT_VERSION}\n")
            temp.write(f"# GENERATED BY: {APP_TITLE}\n")
            temp.write(f"# SCAN STARTED: {result.started_at:%Y-%m-%d %H:%M:%S}\n")
            temp.write(f"# SCAN COMPLETED: {result.completed_at:%Y-%m-%d %H:%M:%S}\n")
            temp.write(f"# REPORT SAVED: {datetime.now():%Y-%m-%d %H:%M:%S}\n")
            temp.write(f"# SCAN DURATION: {result.elapsed_seconds:.3f} seconds\n")
            temp.write(f"# VICTIM / CASE: {safe_report_text(options.victim)}\n")
            temp.write(f"# DOMAIN: https://{safe_report_text(normalize_domain(options.domain))}\n")
            temp.write(f"# ROOT PATH: {safe_report_text(options.root_path)}\n")
            temp.write(f"# SCAN MODE: {safe_report_text(options.deep_mode).upper()}\n")
            temp.write(f"# AGGRESSIVE MAGIC: {'ENABLED' if aggressive_magic else 'DISABLED'}\n")
            temp.write(f"# FILESYSTEM FILES: {c.filesystem_files:,}\n")
            temp.write(f"# FILESYSTEM DIRECTORIES: {c.filesystem_directories:,}\n")
            temp.write(f"# PROCESSED FILES: {c.processed_files:,}\n")
            temp.write(f"# TOTAL REPORT ROWS: {c.report_rows:,}\n")
            temp.write(f"# REAL FILE ENTRIES: {c.real_file_entries:,}\n")
            temp.write(f"# ON-DISK SIZE: {format_size(c.total_size_bytes)}\n")
            temp.write(f"# ON-DISK SIZE BYTES: {c.total_size_bytes}\n")
            temp.write(f"# ARCHIVES FOUND: {c.archives_found:,}\n")
            temp.write(f"# NESTED ARCHIVES FOUND: {c.nested_archives_found:,}\n")
            temp.write(f"# HIDDEN ARCHIVE CANDIDATES: {c.hidden_archives_found:,}\n")
            temp.write(f"# BROKEN ARCHIVES: {c.archives_broken:,}\n")
            temp.write(f"# ENCRYPTED ARCHIVE CONTEXTS: {c.archives_encrypted:,}\n")
            temp.write("# SCOPE: Metadata inventory; not a full content integrity check.\n")
            temp.write("# LIMITS: Solid 7z recursion skipped; no OS-level resource isolation.\n")
            temp.write(f"# WARNINGS: {c.warnings:,}\n")
            temp.write(f"# SKIPPED FILESYSTEM ITEMS: {c.skipped_files:,}\n")
            temp.write(f"# CANCELLED: {'YES' if result.cancelled else 'NO'}\n")
            temp.write(
                "# NOTE: Lines beginning with @ represent archive members. "
                "Archive-member sizes are excluded from the on-disk size total.\n"
            )
            temp.write(
                "# NOTE: This report contains metadata only. "
                "No archive content was extracted to disk.\n\n"
            )

            total = len(result.entries)
            for index, line in enumerate(result.entries, start=1):
                clean = safe_report_text(line)
                encoded = (clean + "\n").encode("utf-8")
                digest.update(encoded)
                temp.write(clean + "\n")
                if progress_callback and (
                    index % SAVE_PROGRESS_EVERY_ROWS == 0 or index == total
                ):
                    progress_callback(index, total)

            temp.write("\n")
            temp.write(f"# DATA LINES SHA256: {digest.hexdigest()}\n")
            temp.flush()
            os.fsync(temp.fileno())

        os.replace(temporary_path, output_path)
        temporary_path = None
        return digest.hexdigest()
    finally:
        if temporary_path is not None:
            try:
                temporary_path.unlink(missing_ok=True)
            except OSError:
                pass
